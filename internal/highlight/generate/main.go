// Command generate writes the stylesheet the highlighted previews refer to.
//
// Chroma emits a class per token type, of which there are far more than a
// palette has colours. The mapping below is by token category, so a category
// covers every type under it in every language chroma knows, and the colours
// themselves are the shared palette's custom properties: a preview follows the
// theme the same way the rest of the window does.
//
// Run it with `go generate ./internal/highlight`.
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/alecthomas/chroma/v2"

	"canopy/internal/highlight"
)

// The same groups the editor next door colours, so code reads alike in both.
const (
	comment     = "color: var(--text-dim); font-style: italic;"
	keyword     = "color: var(--ctx-violet);"
	name        = "color: var(--ctx-blue);"
	text        = "color: var(--ctx-green);"
	number      = "color: var(--ctx-amber);"
	preprocess  = "color: var(--ctx-pink);"
	punctuation = "color: var(--text-muted);"
	problem     = "color: var(--ctx-red);"
)

func main() {
	out := flag.String("out", "", "path of the stylesheet to write")
	flag.Parse()
	if *out == "" {
		fail(fmt.Errorf("-out is required"))
	}
	if err := os.WriteFile(*out, []byte(stylesheet()), 0o644); err != nil {
		fail(err)
	}
}

func stylesheet() string {
	sheet := strings.Builder{}
	sheet.WriteString("/* Generated by internal/highlight/generate. Do not edit. */\n")
	for _, declaration := range declarationOrder() {
		fmt.Fprintf(&sheet, "\n%s {\n\t%s\n}\n", selectorFor(declaration), declaration)
	}
	return sheet.String()
}

// One rule per colour, listing every class that takes it, so the sheet stays
// short enough to read.
func classesByDeclaration() map[string][]string {
	classes := map[string][]string{}
	for tokenType, class := range chroma.StandardTypes {
		declaration := declarationFor(tokenType)
		if declaration == "" || class == "" {
			continue
		}
		classes[declaration] = append(classes[declaration], class)
	}
	return classes
}

func selectorFor(declaration string) string {
	classes := classesByDeclaration()[declaration]
	sort.Strings(classes)
	selectors := make([]string, 0, len(classes))
	for _, class := range classes {
		selectors = append(selectors, "."+highlight.ClassPrefix+class)
	}
	return strings.Join(selectors, ",\n")
}

func declarationOrder() []string {
	declarations := []string{}
	for declaration := range classesByDeclaration() {
		declarations = append(declarations, declaration)
	}
	sort.Strings(declarations)
	return declarations
}

// Plain identifiers and ordinary text get no rule at all: they are the colour
// the pane already writes in.
func declarationFor(tokenType chroma.TokenType) string {
	if tokenType == chroma.Error {
		return problem
	}
	switch tokenType.Category() {
	case chroma.Keyword:
		return keyword
	case chroma.Comment:
		return preprocessorOrComment(tokenType)
	case chroma.Operator, chroma.Punctuation:
		return punctuation
	case chroma.Name:
		return nameDeclaration(tokenType)
	case chroma.Literal:
		return literalDeclaration(tokenType)
	}
	return ""
}

// A preprocessor line is a comment to chroma, but it reads as a directive.
func preprocessorOrComment(tokenType chroma.TokenType) string {
	if tokenType == chroma.CommentPreproc || tokenType == chroma.CommentPreprocFile {
		return preprocess
	}
	return comment
}

// Only the names that carry a line: what is being called, defined or applied.
func nameDeclaration(tokenType chroma.TokenType) string {
	switch tokenType {
	case chroma.NameFunction, chroma.NameFunctionMagic, chroma.NameClass,
		chroma.NameBuiltin, chroma.NameBuiltinPseudo, chroma.NameException,
		chroma.NameNamespace:
		return name
	case chroma.NameDecorator, chroma.NameTag, chroma.NameEntity:
		return preprocess
	case chroma.NameConstant:
		return number
	}
	return ""
}

func literalDeclaration(tokenType chroma.TokenType) string {
	switch tokenType.SubCategory() {
	case chroma.LiteralString:
		return text
	case chroma.LiteralNumber:
		return number
	}
	return number
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
